// Package compose writes docker-compose-generated.yml.
//
// The YAML is built line by line so that the file stays byte-identical to
// the one written by earlier releases: 2-space indentation, no name:, no
// version:, no named volumes. Services come in this order: databases (with
// pgAdmin after PostgreSQL), phpMyAdmin, Redis, Soketi, DNS, the reverse
// proxy, then one FrankenPHP container per PHP version.
package compose

import (
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/leobsst/frankenphp-cli/internal/core/phpversions"
	"github.com/leobsst/frankenphp-cli/internal/core/soketi"
)

const (
	// FileName is the generated compose file, in the data directory.
	FileName = "docker-compose-generated.yml"

	ReverseProxyContainer = "franken-caddy-proxy"
	RedisContainer        = "franken_redis"
	PHPMyAdminContainer   = "franken_phpmyadmin"
	PGAdminContainer      = "franken_pgadmin"
	DNSContainer          = "franken_dns"
	DNSImage              = "coredns/coredns:1.11.3"

	// PHPMyAdminConfigPath is the phpMyAdmin config override, relative to
	// the data directory.
	PHPMyAdminConfigPath = "phpmyadmin/config.user.inc.php"

	// PHPMyAdminConfig logs in to each server with its own root password:
	// the image only takes one PMA_USER/PMA_PASSWORD pair for all of them.
	PHPMyAdminConfig = `<?php
// Generated by FrankenManager: do not edit, overwritten on start.
foreach ($cfg['Servers'] as $i => $server) {
    $password = getenv('FRANKEN_PASSWORD_' . strtoupper($server['host'] ?? ''));
    if ($password !== false) {
        $cfg['Servers'][$i]['auth_type'] = 'config';
        $cfg['Servers'][$i]['user'] = 'root';
        $cfg['Servers'][$i]['password'] = $password;
    }
}
$cfg['ServerDefault'] = 1;
`

	fileMode = 0o644
)

// DBContainers maps each database engine to its container.
var DBContainers = map[string]string{
	"mariadb":    "franken_mariadb",
	"mysql":      "franken_mysql",
	"postgresql": "franken_postgresql",
}

// PMAServer is a database server phpMyAdmin connects to.
type PMAServer struct {
	Engine      string
	Container   string
	Verbose     string // name shown in phpMyAdmin's server switcher
	PasswordVar string // .env variable holding its root password
}

// pmaServers are in the order of the server switcher, the first enabled
// one being the default.
var pmaServers = []PMAServer{
	{"mariadb", "franken_mariadb", "MariaDB", "MARIADB_ROOT_PASSWORD"},
	{"mysql", "franken_mysql", "MySQL", "MYSQL_ROOT_PASSWORD"},
}

// PMAServers returns the servers phpMyAdmin connects to, MariaDB first,
// none when neither MariaDB nor MySQL is enabled.
func PMAServers(dbEngines []string) []PMAServer {
	var servers []PMAServer
	for _, s := range pmaServers {
		if slices.Contains(dbEngines, s.Engine) {
			servers = append(servers, s)
		}
	}
	return servers
}

// Options is what the stack runs.
type Options struct {
	PHPVersions []string // one FrankenPHP container each, in any order
	Production  bool
	DBEngines   []string // nil means ["mariadb"]
	DNSListen   string   // "ip:port" the LAN DNS server listens on, "" for none
	Redis       bool
	Websocket   bool // Soketi
}

// Write writes <dataDir>/docker-compose-generated.yml and, in development
// with phpMyAdmin, its config override. It returns the compose file path.
func Write(dataDir string, o Options) (string, error) {
	o = o.withDefaults()
	if !o.Production && len(PMAServers(o.DBEngines)) > 0 {
		pma := filepath.Join(dataDir, PHPMyAdminConfigPath)
		if err := os.MkdirAll(filepath.Dir(pma), 0o755); err != nil {
			return "", err
		}
		if err := os.WriteFile(pma, []byte(PHPMyAdminConfig), fileMode); err != nil {
			return "", err
		}
	}
	path := filepath.Join(dataDir, FileName)
	return path, os.WriteFile(path, []byte(Build(o)), fileMode)
}

func (o Options) withDefaults() Options {
	if o.DBEngines == nil {
		o.DBEngines = []string{"mariadb"}
	}
	return o
}

// Build returns the content of the compose file.
func Build(o Options) string {
	o = o.withDefaults()
	versions := slices.Sorted(slices.Values(o.PHPVersions))

	lines := []string{"services:"}
	lines = append(lines, dbServices(o.DBEngines, o.Production)...)
	if o.Redis {
		lines = append(lines, redisService(o.Production)...)
	}
	if o.Websocket {
		lines = append(lines, soketi.Service(o.Production)...)
	}
	if o.DNSListen != "" {
		lines = append(lines, dnsService(o.DNSListen)...)
	}
	lines = append(lines, caddyService(versions, o.Production)...)
	for _, v := range versions {
		lines = append(lines, phpService(v, o)...)
	}
	if !o.Production {
		lines = append(lines,
			"networks:",
			"  franken_network:",
			"    driver: bridge",
		)
	}
	return strings.Join(lines, "\n") + "\n"
}

// dir returns the host path of a ${VAR} directory: relative to the data
// directory in development, to ${PWD} in production.
func dir(variable, def string, production bool) string {
	if production {
		return "${" + variable + ":-${PWD}/" + def + "}"
	}
	return "${" + variable + ":-./" + def + "}"
}

// healthcheck returns a healthcheck block.
func healthcheck(test, startPeriod string) []string {
	return []string{
		"    healthcheck:",
		"      test: " + test,
		"      interval: 10s",
		"      timeout: 5s",
		"      retries: 5",
		"      start_period: " + startPeriod,
	}
}

// devNetwork is the network of the services that do not use the host's.
var devNetwork = []string{"    networks:", "      - franken_network"}

// dbEngine describes a database service.
type dbEngine struct {
	image    string
	mysqlCmd bool   // --max-allowed-packet and user: ${UID}:${GID}
	dataDir  string // in the container
	portVar  string // development port binding, e.g. ${DB_PORT:-...}
	env      []string
	test     string
}

var dbEngines = map[string]dbEngine{
	"mariadb": {
		image:    "mariadb:${MARIADB_VERSION:-10.11.9}",
		mysqlCmd: true,
		dataDir:  "/var/lib/mysql",
		portVar:  "${DB_PORT:-127.0.0.1:3306:3306}",
		env:      []string{"MARIADB_ROOT_PASSWORD: ${MARIADB_ROOT_PASSWORD}"},
		test:     `["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]`,
	},
	"mysql": {
		image:    "mysql:${MYSQL_VERSION:-8.0}",
		mysqlCmd: true,
		dataDir:  "/var/lib/mysql",
		portVar:  "${MYSQL_PORT:-127.0.0.1:3307:3306}",
		env:      []string{"MYSQL_ROOT_PASSWORD: ${MYSQL_ROOT_PASSWORD}"},
		test:     `["CMD", "mysqladmin", "ping", "-h", "localhost"]`,
	},
	"postgresql": {
		image:   "postgres:${POSTGRES_VERSION:-16}-alpine",
		dataDir: "/var/lib/postgresql/data",
		portVar: "${POSTGRES_PORT:-127.0.0.1:5432:5432}",
		env: []string{
			"POSTGRES_USER: ${POSTGRES_USER:-postgres}",
			"POSTGRES_PASSWORD: ${POSTGRES_PASSWORD}",
		},
		test: `["CMD-SHELL", "pg_isready -U ${POSTGRES_USER:-postgres}"]`,
	},
}

// dbServices returns the database services in DB_ENGINES order, pgAdmin
// right after PostgreSQL and phpMyAdmin last (both in development only).
func dbServices(engines []string, production bool) []string {
	var lines []string
	for _, engine := range engines {
		e, ok := dbEngines[engine]
		if !ok {
			continue
		}
		lines = append(lines,
			"  db-"+engine+":",
			"    container_name: "+DBContainers[engine],
			"    image: "+e.image,
			"    restart: always",
		)
		if e.mysqlCmd {
			lines = append(lines, "    command: --max-allowed-packet=${MYSQL_MAX_ALLOWED_PACKET:-512M}")
		}
		if production {
			lines = append(lines, "    network_mode: host")
		}
		if e.mysqlCmd {
			lines = append(lines, "    user: ${UID}:${GID}")
		}
		lines = append(lines,
			"    env_file: .env",
			"    volumes:",
			"      - "+dir("DATABASE_DIR", "database", production)+"/"+engine+":"+e.dataDir,
		)
		if !production {
			lines = append(lines, "    ports:", "      - "+e.portVar)
		}
		lines = append(lines, "    environment:")
		for _, v := range e.env {
			lines = append(lines, "      "+v)
		}
		if !production {
			lines = append(lines, devNetwork...)
		}
		lines = append(lines, healthcheck(e.test, "30s")...)
		lines = append(lines, "")

		if engine == "postgresql" && !production {
			lines = append(lines, pgAdminService()...)
		}
	}
	if !production {
		lines = append(lines, phpMyAdminService(engines)...)
	}
	return lines
}

func pgAdminService() []string {
	return []string{
		"  pgadmin:",
		"    container_name: " + PGAdminContainer,
		"    image: dpage/pgadmin4:latest",
		"    restart: always",
		"    environment:",
		"      PGADMIN_DEFAULT_EMAIL: ${PGADMIN_EMAIL:-admin@admin.com}",
		"      PGADMIN_DEFAULT_PASSWORD: ${POSTGRES_PASSWORD}",
		"      PGADMIN_CONFIG_SERVER_MODE: 'False'",
		"    ports:",
		"      - ${PGADMIN_PORT:-127.0.0.1:8081:80}",
		"    depends_on:",
		"      db-postgresql:",
		"        condition: service_healthy",
		"    networks:",
		"      - franken_network",
		"",
	}
}

// phpMyAdminService serves every enabled MariaDB and MySQL server, none
// when neither is enabled.
func phpMyAdminService(engines []string) []string {
	servers := PMAServers(engines)
	if len(servers) == 0 {
		return nil
	}
	var hosts, verboses, ports []string
	for _, s := range servers {
		hosts = append(hosts, s.Container)
		verboses = append(verboses, s.Verbose)
		ports = append(ports, "3306")
	}
	lines := []string{
		"  phpmyadmin:",
		"    container_name: " + PHPMyAdminContainer,
		"    image: phpmyadmin:latest",
		"    restart: always",
		"    environment:",
		"      PMA_HOSTS: " + strings.Join(hosts, ","),
		"      PMA_VERBOSES: " + strings.Join(verboses, ","),
		"      PMA_PORTS: " + strings.Join(ports, ","),
	}
	for _, s := range servers {
		lines = append(lines, "      FRANKEN_PASSWORD_"+strings.ToUpper(s.Container)+": ${"+s.PasswordVar+"}")
	}
	lines = append(lines,
		"    volumes:",
		"      - ./"+PHPMyAdminConfigPath+":/etc/phpmyadmin/config.user.inc.php:ro",
		"    ports:",
		"      - ${PMA_PORT:-127.0.0.1:8080:80}",
		"    depends_on:",
	)
	for _, s := range servers {
		lines = append(lines, "      db-"+s.Engine+":", "        condition: service_healthy")
	}
	return append(lines, "    networks:", "      - franken_network", "")
}

func redisService(production bool) []string {
	lines := []string{
		"  cache:",
		"    container_name: " + RedisContainer,
		"    image: redis:alpine",
		"    restart: always",
	}
	if production {
		lines = append(lines, "    network_mode: host", "    command: redis-server")
	} else {
		lines = append(lines, "    command: redis-server", "    ports:", "      - ${REDIS_PORT:-127.0.0.1:6379:6379}")
		lines = append(lines, devNetwork...)
	}
	lines = append(lines, healthcheck(`["CMD", "redis-cli", "ping"]`, "10s")...)
	return append(lines, "")
}

// dnsService publishes the LAN DNS server on listen, on its own default
// network: it only needs to reach the upstream resolvers.
func dnsService(listen string) []string {
	return []string{
		"  dns:",
		"    container_name: " + DNSContainer,
		"    image: " + DNSImage,
		"    restart: always",
		"    command: -conf /etc/coredns/Corefile",
		"    volumes:",
		"      - ./dns:/etc/coredns:ro",
		"    ports:",
		`      - "` + listen + `:53/udp"`,
		`      - "` + listen + `:53/tcp"`,
		"",
	}
}

// serviceName is the compose service of a PHP version, e.g. franken-php-83.
func serviceName(version string) string {
	return "franken-php-" + strings.ReplaceAll(version, ".", "")
}

// caddyService is the reverse proxy, on the host network in every mode so
// that PHP apps reach the other domains through /etc/hosts.
func caddyService(versions []string, production bool) []string {
	caddy := dir("CADDY_DIR", "caddy", production)
	lines := []string{
		"  caddy-proxy:",
		"    container_name: " + ReverseProxyContainer,
		"    image: caddy:2-alpine",
		"    restart: always",
		"    network_mode: host",
		"    volumes:",
		"      - " + caddy + "/Caddyfile:/etc/caddy/Caddyfile",
		"      - " + caddy + "/certs:/certs",
		"      - " + caddy + "/data:/data",
		"      - " + caddy + "/config:/config",
		"      - " + caddy + "/log:/var/log",
	}
	if production {
		lines = append(lines, "      - /etc/letsencrypt:/etc/letsencrypt")
	}
	if len(versions) > 0 {
		lines = append(lines, "    depends_on:")
		for _, v := range versions {
			lines = append(lines, "      "+serviceName(v)+":", "        condition: service_started")
		}
	}
	return append(lines, "")
}

// phpService is the FrankenPHP container of a version, on the host
// network, listening on its own internal ports. Versions are validated
// upstream: an unknown one gets port 0.
func phpService(version string, o Options) []string {
	httpPort, httpsPort, _ := phpversions.InternalPorts(version)
	caddy := dir("CADDY_DIR", "caddy", o.Production)
	iniDir := "./php/" + version
	if o.Production {
		iniDir = "${PWD}/php/" + version
	}

	lines := []string{
		"  " + serviceName(version) + ":",
		"    container_name: " + phpversions.ContainerName(version),
		"    image: " + phpversions.ImageName(version),
		"    restart: always",
		"    network_mode: host",
	}
	if o.Production {
		lines = append(lines, "    user: ${UID}:${GID}")
	}
	lines = append(lines,
		"    environment:",
		"      WEB_HTTP_PORT: '"+strconv.Itoa(httpPort)+"'",
		"      WEB_HTTPS_PORT: '"+strconv.Itoa(httpsPort)+"'",
		"    volumes:",
		"      - ${CUSTOM_PATH}:/${CUSTOM_PATH}",
		"      - "+caddy+"/Caddyfile.worker:/etc/caddy/Caddyfile",
		"      - "+caddy+"/sites/php-"+version+":/etc/caddy/sites/custom",
		"      - "+caddy+"/certs:/certs",
		"      - "+caddy+"/log:/var/log",
		"      - "+iniDir+"/php.ini:/usr/local/etc/php/php.ini",
	)
	if o.Production {
		lines = append(lines, "      - "+iniDir+"/php-prod.ini:/usr/local/etc/php/conf.d/99-production.ini")
	}

	var deps []string
	for _, engine := range o.DBEngines {
		deps = append(deps, "      db-"+engine+":", "        condition: service_healthy")
	}
	if o.Redis {
		deps = append(deps, "      cache:", "        condition: service_healthy")
	}
	if len(deps) > 0 {
		lines = append(lines, "    depends_on:")
		lines = append(lines, deps...)
	}
	return append(lines, "")
}
