// The helper keeps the checks of the one earlier releases installed; only
// the removal changes, so that it also works on Linux.
func TestHelperScript(t *testing.T) {
	s := HelperScript("/etc/hosts")
	for _, want := range []string{
		`HOSTS_FILE="/etc/hosts"`,
		`if [[ "$IP" != "127.0.0.1" && "$IP" != "::1" ]]; then`,
		`if [[ -z "$HOSTNAME" || "$HOSTNAME" == "localhost" ]]; then`,
		`=~ ^[a-zA-Z0-9][a-zA-Z0-9.-]*[a-zA-Z0-9]$ ]]`,
		`echo -e "$IP\t$HOSTNAME" >> "$HOSTS_FILE"`,
		`grep -Ev "$PATTERN" "$HOSTS_FILE" > "$TMP_FILE" || true`,
		`cat "$TMP_FILE" > "$HOSTS_FILE"`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("helper misses %q", want)
		}
	}
	if strings.Contains(s, "sed -E") {
		t.Error("helper still uses sed")
	}
}

func TestSetupUnix(t *testing.T) {
	t.Setenv("SUDO_USER", "leo")
	m, r, log := newManager(t, "linux", true)
	if err := os.MkdirAll(filepath.Dir(m.SudoersPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if m.Configured() || m.UpToDate() {
		t.Fatal("configured before setup")
	}
	if err := m.Setup(context.Background()); err != nil {
		t.Fatal(err)
	}

	if data, _ := os.ReadFile(m.HelperPath); string(data) != HelperScript(m.HostsPath) {
		t.Error("helper not written")
	}
	if info, _ := os.Stat(m.HelperPath); info.Mode().Perm() != 0o755 {
		t.Errorf("helper mode %v", info.Mode())
	}
	data, _ := os.ReadFile(m.SudoersPath)
	if string(data) != SudoersContent("leo", m.HelperPath, m.SudoersPath) {
		t.Errorf("sudoers:\n%s", data)
	}
	if info, _ := os.Stat(m.SudoersPath); info.Mode().Perm() != 0o440 {
		t.Errorf("sudoers mode %v", info.Mode())
	}
	entries, _ := os.ReadDir(filepath.Dir(m.SudoersPath))
	if len(entries) != 1 {
		t.Errorf("temporary file left: %v", entries)
	}
	if len(r.Calls) != 1 || r.Calls[0].Name != "visudo" || r.Calls[0].Args[0] != "-c" {
		t.Errorf("calls = %v", r.Lines())
	}
	if !m.Configured() || !m.UpToDate() {
		t.Error("not configured after setup")
	}
	want := []string{
		"info: Creating helper script at " + m.HelperPath,
		"info: Installing sudoers configuration at " + m.SudoersPath,
		"success: Privilege configuration complete!",
		"info: You can now run frankenmanager start/stop without sudo prompts",
	}
	if !slices.Equal(log.Lines, want) {
		t.Errorf("log = %v", log.Lines)
	}

	// An outdated helper (from an earlier release) is detected
	if err := os.WriteFile(m.HelperPath, []byte("old"), 0o755); err != nil {
		t.Fatal(err)
	}
	if !m.Configured() || m.UpToDate() {
		t.Error("outdated helper not detected")
	}
}

func TestSetupUnixRejectsInvalidSudoers(t *testing.T) {
	m, r, _ := newManager(t, "darwin", true)
	if err := os.MkdirAll(filepath.Dir(m.SudoersPath), 0o755); err != nil {
		t.Fatal(err)
	}
	r.Handle = func(command.Cmd) (command.Result, error) {
		return command.Result{ExitCode: 1, Stderr: []byte("syntax error")}, nil
	}
	err := m.Setup(context.Background())
	if err == nil || err.Error() != "Failed to configure sudoers: Invalid sudoers syntax: syntax error" {
		t.Errorf("err = %v", err)
	}
	if entries, _ := os.ReadDir(filepath.Dir(m.SudoersPath)); len(entries) != 0 {
		t.Errorf("sudoers installed anyway: %v", entries)
	}
}

func TestSetupAndRemoveNeedRoot(t *testing.T) {
	m, _, _ := newManager(t, "linux", false)
	if err := m.Setup(context.Background()); err == nil ||
		err.Error() != "Setup requires root privileges. Please run with: sudo frankenmanager setup" {
		t.Errorf("setup: %v", err)
	}
	if err := m.Remove(); err == nil || !strings.HasPrefix(err.Error(), "Removal requires root privileges.") {
		t.Errorf("remove: %v", err)
	}
}

func TestRemoveUnix(t *testing.T) {
	m, _, log := newManager(t, "linux", true)
	if err := m.Remove(); err != nil {
		t.Fatal(err)
	}
	for _, p := range []string{m.HelperPath, m.SudoersPath} {
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, nil, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := m.Remove(); err != nil {
		t.Fatal(err)
	}
	if exists(m.HelperPath) || exists(m.SudoersPath) {
		t.Error("files left")
	}
	want := []string{
		"info: No privilege configuration found",
		"info: Removing helper script: " + m.HelperPath,
		"info: Removing sudoers configuration: " + m.SudoersPath,
		"success: Privilege configuration removed",
	}
	if !slices.Equal(log.Lines, want) {
		t.Errorf("log = %v", log.Lines)
	}
}

func TestCanUseHelper(t *testing.T) {
	m, r, _ := newManager(t, "darwin", false)
	ctx := context.Background()
	if m.CanUseHelper(ctx) || len(r.Calls) != 0 {
		t.Fatal("usable while not configured")
	}
	for _, p := range []string{m.HelperPath, m.SudoersPath} {
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		_ = os.WriteFile(p, nil, 0o600)
	}
	// The helper rejects --help, but sudo did not ask for a password
	r.Handle = func(command.Cmd) (command.Result, error) {
		return command.Result{ExitCode: 1, Stderr: []byte("Error: Action must be 'add' or 'remove'")}, nil
	}
	if !m.CanUseHelper(ctx) {
		t.Error("helper not usable")
	}
	if got := r.Lines()[0]; got != "sudo -n "+m.HelperPath+" --help" {
		t.Errorf("probe = %s", got)
	}
	r.Handle = func(command.Cmd) (command.Result, error) {
		return command.Result{ExitCode: 1, Stderr: []byte("sudo: a password is required")}, nil
	}
	if m.CanUseHelper(ctx) {
		t.Error("helper usable without NOPASSWD")
	}
}

func TestRunHelper(t *testing.T) {
	m, r, _ := newManager(t, "linux", false)
	ctx := context.Background()
	if _, err := m.RunHelper(ctx, "add", "127.0.0.1", "a.test"); err == nil ||
		err.Error() != "Helper script not installed. Run 'frankenmanager setup' first." {
		t.Errorf("err = %v", err)
	}
	_ = os.WriteFile(m.HelperPath, nil, 0o755)
	r.Handle = func(c command.Cmd) (command.Result, error) {
		if c.Args[1] == "remove" {
			return command.Result{ExitCode: 1, Stdout: []byte("Entry not found\n")}, nil
		}
		return command.Result{Stdout: []byte("Added 127.0.0.1 a.test\n")}, nil
	}
	if out, err := m.RunHelper(ctx, "add", "127.0.0.1", "a.test"); err != nil || out != "Added 127.0.0.1 a.test" {
		t.Errorf("add = %q, %v", out, err)
	}
	if _, err := m.RunHelper(ctx, "remove", "::1", "a.test"); err == nil || err.Error() != "Entry not found" {
		t.Errorf("remove err = %v", err)
	}
	if got := r.Lines()[0]; got != "sudo "+m.HelperPath+" add 127.0.0.1 a.test" {
		t.Errorf("call = %s", got)
	}
}

// Windows: no PowerShell helper, an Administrator terminal instead.
func TestWindows(t *testing.T) {
	m, r, log := newManager(t, "windows", false)
	ctx := context.Background()
	if err := m.Setup(ctx); err == nil || err.Error() != "Administrator privileges required" {
		t.Errorf("setup as user: %v", err)
	}
	if log.Lines[0] != "error: Setup requires Administrator privileges." {
		t.Errorf("log = %v", log.Lines)
	}

	m.IsAdmin = func() bool { return true }
	_ = os.MkdirAll(filepath.Dir(m.WindowsHelperPath), 0o755)
	_ = os.WriteFile(m.WindowsHelperPath, nil, 0o644)
	if err := m.Setup(ctx); err != nil {
		t.Fatal(err)
	}
	if exists(filepath.Dir(m.WindowsHelperPath)) {
		t.Error("PowerShell helper left by setup")
	}
	if !m.Configured() || !m.CanUseHelper(ctx) || !m.UpToDate() || len(r.Calls) != 0 {
		t.Errorf("writable hosts file not configured: calls %v", r.Lines())
	}
	s := m.Status(ctx)
	if s.Platform != "windows" || !s.Configured || !s.IsAdmin || s.HelperInstalled || s.SudoersConfigured {
		t.Errorf("status = %+v", s)
	}
	if err := m.Remove(); err != nil {
		t.Fatal(err)
	}
}
