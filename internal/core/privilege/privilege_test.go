// newManager returns a Manager whose files live in a temporary directory.
func newManager(t *testing.T, goos string, admin bool) (*Manager, *commandtest.Runner, *commandtest.Log) {
	t.Helper()
	dir := t.TempDir()
	hosts := filepath.Join(dir, "hosts")
	if err := os.WriteFile(hosts, []byte("127.0.0.1\tlocalhost\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	r := &commandtest.Runner{}
	log := &commandtest.Log{}
	return &Manager{
		GOOS:              goos,
		HostsPath:         hosts,
		HelperPath:        filepath.Join(dir, "frankenmanager-hosts-helper"),
		SudoersPath:       filepath.Join(dir, "sudoers.d", "frankenmanager"),
		WindowsHelperPath: filepath.Join(dir, "AppData", "FrankenManager", windowsHelperName),
		Run:               r,
		Log:               log,
		IsAdmin:           func() bool { return admin },
		Owner:             func(string, int, int) error { return nil },
	}, r, log
}

