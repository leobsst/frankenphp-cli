package resources

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
	"testing/fstest"

	assets "github.com/leobsst/frankenphp-cli"
)

type recorder struct{ lines []string }

func (r *recorder) Info(msg string)    { r.lines = append(r.lines, "info: "+msg) }
func (r *recorder) Warning(msg string) { r.lines = append(r.lines, "warning: "+msg) }

func newTestExtractor(t *testing.T, version string) (*Extractor, *recorder) {
	t.Helper()
	t.Setenv("SUDO_UID", "") // never chown in tests
	files := fstest.MapFS{}
	for _, name := range assets.Files {
		files[name] = &fstest.MapFile{Data: []byte(name + " " + version)}
	}
	log := &recorder{}
	return &Extractor{
		Dir:     filepath.Join(t.TempDir(), "data"),
		Assets:  files,
		Files:   assets.Files,
		Static:  assets.StaticFiles,
		Version: version,
		Log:     log,
	}, log
}

func read(t *testing.T, e *Extractor, name string) string {
	t.Helper()
	data, err := os.ReadFile(e.path(filepath.FromSlash(name)))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func write(t *testing.T, e *Extractor, name, content string) {
	t.Helper()
	p := e.path(filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestFirstRunExtractsEverything(t *testing.T) {
	e, log := newTestExtractor(t, "2.0.0")
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}

	for _, name := range assets.Files {
		if got := read(t, e, name); got != name+" 2.0.0" {
			t.Errorf("%s = %q", name, got)
		}
	}
	for _, dir := range []string{
		"caddy/sites/archive", "caddy/sites/php-8.5", "caddy/certs",
		"caddy/log/caddy", "caddy/log/php", "caddy/data", "caddy/config", "php/8.2", "database",
	} {
		if info, err := os.Stat(e.path(filepath.FromSlash(dir))); err != nil || !info.IsDir() {
			t.Errorf("directory %s missing", dir)
		}
	}
	// Every version gets its own copy of the base php.ini files
	for _, name := range []string{"php/8.3/php.ini", "php/8.3/php-prod.ini"} {
		if got, want := read(t, e, name), read(t, e, "php/"+filepath.Base(name)); got != want {
			t.Errorf("%s = %q, want %q", name, got, want)
		}
	}
	if read(t, e, InitializedMarker) != "1" || read(t, e, VersionMarker) != "2.0.0" {
		t.Error("markers not written")
	}
	want := []string{
		"info: Initializing FrankenManager data directory: " + e.Dir,
		"info: FrankenManager initialized successfully.",
	}
	if strings.Join(log.lines, "\n") != strings.Join(want, "\n") {
		t.Errorf("log = %q, want %q", log.lines, want)
	}
}

func TestSameVersionTouchesNothing(t *testing.T) {
	e, _ := newTestExtractor(t, "2.0.0")
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	write(t, e, "Dockerfile", "edited")

	log := &recorder{}
	e.Log = log
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	if got := read(t, e, "Dockerfile"); got != "edited" {
		t.Errorf("Dockerfile rewritten without a version change: %q", got)
	}
	if len(log.lines) != 0 {
		t.Errorf("unexpected messages: %q", log.lines)
	}
}

// A version change rewrites the static files only: the main Caddyfile is
// regenerated by the CLI and the per-version php.ini copies are the user's.
func TestVersionChangeSyncsStaticFilesOnly(t *testing.T) {
	e, _ := newTestExtractor(t, "1.0.0")
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	write(t, e, "caddy/Caddyfile", "generated")
	write(t, e, "php/8.3/php.ini", "user")
	write(t, e, ".env", "user env")

	e2, _ := newTestExtractor(t, "2.0.0")
	e2.Dir = e.Dir
	if err := e2.Ensure(); err != nil {
		t.Fatal(err)
	}

	for _, name := range assets.StaticFiles {
		if got := read(t, e, name); got != name+" 2.0.0" {
			t.Errorf("%s not synced: %q", name, got)
		}
	}
	for name, want := range map[string]string{
		"caddy/Caddyfile": "generated",
		"php/8.3/php.ini": "user",
		".env":            "user env",
	} {
		if got := read(t, e, name); got != want {
			t.Errorf("%s overwritten: %q", name, got)
		}
	}
	if read(t, e, VersionMarker) != "2.0.0" {
		t.Error("version marker not updated")
	}
}

// Docker leaves an empty directory where a mounted file was missing.
func TestFirstRunReplacesDirectoriesAtFilePaths(t *testing.T) {
	e, log := newTestExtractor(t, "2.0.0")
	stray := e.path("caddy", "Caddyfile")
	if err := os.MkdirAll(stray, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	if got := read(t, e, "caddy/Caddyfile"); got != "caddy/Caddyfile 2.0.0" {
		t.Errorf("caddy/Caddyfile = %q", got)
	}
	if !strings.Contains(strings.Join(log.lines, "\n"), "warning: Removed incorrectly created directory: "+stray) {
		t.Errorf("no warning in %q", log.lines)
	}
}

func TestSyncInstalled(t *testing.T) {
	e, _ := newTestExtractor(t, "1.0.0")
	if done, err := e.SyncInstalled(); err != nil || done {
		t.Fatalf("uninitialized directory: done=%v err=%v, want false, nil", done, err)
	}
	if _, err := os.Stat(e.Dir); err == nil {
		t.Error("uninitialized directory created")
	}

	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	e.Version = "2.0.0"
	e.Assets.(fstest.MapFS)["Dockerfile"].Data = []byte("Dockerfile 2.0.0")
	if done, err := e.SyncInstalled(); err != nil || !done {
		t.Fatalf("done=%v err=%v, want true, nil", done, err)
	}
	if got := read(t, e, "Dockerfile"); got != "Dockerfile 2.0.0" {
		t.Errorf("Dockerfile = %q", got)
	}
}

func TestEnsurePHPVersionConfigKeepsExistingCopies(t *testing.T) {
	e, _ := newTestExtractor(t, "2.0.0")
	if err := e.Ensure(); err != nil {
		t.Fatal(err)
	}
	write(t, e, "php/8.4/php.ini", "user")
	if err := os.Remove(e.path("php", "8.4", "php-prod.ini")); err != nil {
		t.Fatal(err)
	}
	if err := e.EnsurePHPVersionConfig("8.4"); err != nil {
		t.Fatal(err)
	}
	if got := read(t, e, "php/8.4/php.ini"); got != "user" {
		t.Errorf("php.ini overwritten: %q", got)
	}
	if got := read(t, e, "php/8.4/php-prod.ini"); got != "php/php-prod.ini 2.0.0" {
		t.Errorf("php-prod.ini not restored: %q", got)
	}
}

func TestPermissionErrorExplainsTheFix(t *testing.T) {
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs Unix permissions and a non-root user")
	}
	e, _ := newTestExtractor(t, "2.0.0")
	if err := os.MkdirAll(e.Dir, 0o500); err != nil { // read-only data directory
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(e.Dir, 0o755) })

	err := e.Ensure()
	if err == nil || !strings.Contains(err.Error(), `sudo chown -R "$(whoami)" "`+e.Dir+`"`) {
		t.Errorf("error = %v, want the chown hint", err)
	}
}
